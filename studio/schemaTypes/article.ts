import {defineField, defineType} from 'sanity'
import {DocumentTextIcon} from '@sanity/icons/DocumentText'

export const article = defineType({
  name: 'article',
  type: 'document',
  icon: DocumentTextIcon,
  groups: [
    {name: 'story', title: 'Story', default: true},
    {name: 'media', title: 'Media & links'},
    {name: 'seo', title: 'SEO & sharing'},
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Headline',
      type: 'string',
      group: 'story',
      validation: (rule) => rule.required().max(120),
    }),
    defineField({
      name: 'slug',
      type: 'slug',
      group: 'story',
      options: {source: 'title', maxLength: 96},
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'excerpt',
      title: 'Subheadline / excerpt',
      type: 'text',
      rows: 3,
      group: 'story',
      description: 'Shown on story cards and in WhatsApp/social previews.',
      validation: (rule) => rule.required().max(200),
    }),
    defineField({
      name: 'category',
      type: 'reference',
      to: [{type: 'category'}],
      group: 'story',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'author',
      type: 'reference',
      to: [{type: 'author'}],
      group: 'story',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'publishedAt',
      title: 'Published at',
      type: 'datetime',
      group: 'story',
      initialValue: () => new Date().toISOString(),
      validation: (rule) => rule.required(),
    }),
    defineField({name: 'updatedAt', title: 'Updated at', type: 'datetime', group: 'story'}),
    defineField({
      name: 'featured',
      type: 'boolean',
      group: 'story',
      description: 'Show in the large slot on the homepage.',
      initialValue: false,
    }),
    defineField({name: 'tags', type: 'array', of: [{type: 'string'}], options: {layout: 'tags'}, group: 'story'}),
    defineField({
      name: 'cover',
      title: 'Cover image',
      type: 'figure',
      group: ['story', 'media'],
      validation: (rule) => rule.required(),
    }),
    defineField({name: 'body', type: 'blockContent', group: 'story', validation: (rule) => rule.required()}),
    defineField({
      name: 'gallery',
      type: 'array',
      of: [{type: 'figure'}],
      group: 'media',
      options: {layout: 'grid'},
    }),
    defineField({
      name: 'sourceUrl',
      title: 'Source URL',
      type: 'url',
      group: 'media',
      description: 'Link to the original report or post, shown as "Originally reported by…".',
    }),
    defineField({
      name: 'embedUrl',
      title: 'Embed URL',
      type: 'url',
      group: 'media',
      description: 'YouTube, SoundCloud, Zeno, X or TikTok link shown as a player under the cover.',
      validation: (rule) => rule.uri({scheme: ['https']}),
    }),
    defineField({
      name: 'seo',
      title: 'SEO',
      type: 'object',
      group: 'seo',
      options: {collapsible: true},
      description: 'Optional — falls back to headline, excerpt and cover image.',
      fields: [
        defineField({name: 'title', type: 'string', validation: (rule) => rule.max(70)}),
        defineField({name: 'description', type: 'text', rows: 2, validation: (rule) => rule.max(160)}),
        defineField({name: 'image', title: 'Social image', type: 'image'}),
      ],
    }),
  ],
  orderings: [{title: 'Newest first', name: 'publishedDesc', by: [{field: 'publishedAt', direction: 'desc'}]}],
  preview: {
    select: {title: 'title', author: 'author.name', category: 'category.title', media: 'cover'},
    prepare: ({title, author, category, media}) => ({
      title,
      subtitle: [category, author].filter(Boolean).join(' · '),
      media,
    }),
  },
})
